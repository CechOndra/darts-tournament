// One-off generator: picks icons from the local-only component-IDEAS/game-icons.net.svg folder
// and writes src/assets/placeholderIcons.ts (path data only). Icons: game-icons.net, CC BY 3.0.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = 'component-IDEAS/game-icons.net.svg/icons/ffffff/000000/1x1';
const PLAYER = ['ninja-head', 'viking-head', 'pirate-captain', 'wizard-face', 'samurai-helmet', 'robot-helmet', 'king', 'chef-toque', 'monk-face', 'cyclops', 'goblin-head', 'ogre', 'vampire-dracula', 'mummy-head', 'bat-mask', 'skull-mask', 'beard', 'woman-elf-face', 'alien-stare', 'jester-hat', 'cowboy-holster', 'headband-knot', 'mustache', 'santa-hat', 'headphones', 'knight-banner', 'gargoyle', 'bully-minion', 'lightning-mask', 'spider-mask'];
const TEAM = ['bull', 'wolf-head', 'eagle-head', 'lion', 'tiger-head', 'shark-jaws', 'dragon-head', 'owl', 'fox-head', 'bear-head', 'snake', 'scorpion', 'horse-head', 'gorilla', 'octopus', 'crab', 'stag-head', 'boar', 'ram', 'penguin', 'bee', 'mammoth', 'unicorn', 'cobra', 'spider-face', 'crown', 'anvil', 'rocket', 'lightning-storm', 'skull-crossed-bones'];

const files = new Map();
for (const author of readdirSync(root)) for (const f of readdirSync(join(root, author))) if (!files.has(f)) files.set(f, author);

const build = (names) =>
  names.map((n) => {
    const author = files.get(`${n}.svg`);
    if (!author) throw new Error(`icon not found: ${n}`);
    const d = readFileSync(join(root, author, `${n}.svg`), 'utf8').match(/<path fill="#fff" d="([^"]+)"/)?.[1];
    if (!d) throw new Error(`no path in ${n}`);
    return { id: n, author, d };
  });

const out = `// GENERATED by scripts/build-placeholder-icons.mjs. Icons from game-icons.net (CC BY 3.0, see CREDITS.md).
export interface PlaceholderIcon {
  id: string;
  author: string;
  /** SVG path data, 512x512 viewBox. */
  d: string;
}
export const PLAYER_ICONS: PlaceholderIcon[] = ${JSON.stringify(build(PLAYER))};
export const TEAM_ICONS: PlaceholderIcon[] = ${JSON.stringify(build(TEAM))};
`;
writeFileSync('src/assets/placeholderIcons.ts', out);
console.log('ok', PLAYER.length, TEAM.length);
